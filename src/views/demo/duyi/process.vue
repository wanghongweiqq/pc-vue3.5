    <h2>进程（Process）和线程（Thread）</h2>
    <p>进程（Process）和线程（Thread）是操作系统中两个最核心的并发执行单位，简单说：进程是“资源分配的基本单位”，线程是“CPU调度的基本单位”。一个进程可以包含多个线程，它们共享进程的资源，但各自独立调度。</p>
    <h4>形象类比</h4>
    <p>进程 = 一家工厂：有独立的厂房、仓库、水电（内存、文件句柄、环境变量）。</p>
    <p>线程 = 工厂里的工人：共享厂房和仓库，各自干活（执行路径），可以并行搬运，但都从同一个仓库取料。</p>
    <p>开新工厂（新进程）= 成本高、隔离好；雇新工人（新线程）= 成本低、协作方便但容易互相踩踏（竞态条件）。</p>
    
    <h3>进程（Process）</h3>
    <p>资源分配的基本单位。程序运行需要有它自己专属的内存空间，可以把这块内存空间简单的理解为进程</p>
    <p>每个应用至少有一个进程，进程之间相互独立，即使要通信，也需要双方同意。</p>
    <p>
