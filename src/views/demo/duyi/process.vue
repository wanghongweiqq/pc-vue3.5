    <h3>线程（Thread）</h3>
    <p>CPU调度的基本单位。一个形象的比喻是：运行代码的 人 称之为 线程。</p>
    <p>一个进程至少有一个线程，所以在进程开启后会自动创建一个线程来运行代码，该线程称之为主线程。</p>
    <p>如果程序需要同时执行多块代码，主线程就会启动更多的线程来执行代码，所以一个进程中可以包含多个线程。</p>
    <p>
      <img
        src="@/assets/images/thread-1.png"
        alt="线程"
        width="600"
      >
    </p>

    <h3>浏览器有哪些进程和线程?</h3>
    <p>浏览器是一个多进程多线程的应用程序</p>
    <p>浏览器内部工作极其复杂。为了避免相互影响，为了减少连环崩溃的几率，当启动浏览器后，它会自动启动多个进程。</p>
    <p>
      <img
        src="@/assets/images/process-3.png"
        alt="浏览器线程"
        width="600"
      >
    </p>
    <h4>其中，最主要的进程有:</h4>
    <h5>1.浏览器进程</h5>
    <p>主要负责界面显示、用户交互、子进程管理等。浏览器进程内部会启动多个线程处理不同的任务。</p>
    <h5>2.网络进程 </h5>
    <p>负责加载网络资源。网络进程内部会启动多个线程来处理不同的网络任务。</p>
    <h5>3.渲染进程</h5>
    <p>渲染进程启动后，会开启一个<em>渲染主线程</em>，主线程负责执行 HTML、CSS、JS 代码。</p>
    <p>默认情况下，浏览器会为每个标签页开启一个新的渲染进程，以保证不同的标签页之间不相互影响。</p>

    <h4>渲染主线程是如何工作的?</h4>
    <p>渲染主线程是浏览器中最繁忙的线程，需要它处理的任务包括但不限于:</p>
    <ul class="ul">
      <li>解析 HTML</li>
      <li>解析 CSS</li>
      <li>计算样式</li>
      <li>布局</li>
      <li>处理图层</li>
      <li>每秒把页面画60次</li>
      <li>执行全局 JS代码</li>
      <li>执行事件处理函数</li>
      <li>执行计时器的回调函数</li>
    </ul>

