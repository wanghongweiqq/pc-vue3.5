    <h2>事件循环（消息循环）</h2>

    <h3>任务分类：同步任务和异步任务</h3>
    <p>JavaScript是一门单线程执行的语言，在同一个时间只能做一件事情。这是因为它运行在浏览器的渲染主线程中，而渲染主线程只有一个。这就导致后面的任务需要等到前面的任务完成才能执行，如果前面的任务很耗时就会造成后面的任务一直等待。为了解决这个问题JS中出现了同步任务和异步任务。</p>

    <h4>同步任务</h4>
    <p>在主线程上排队执行的任务只有前一个任务执行完毕，才能执行后一个任务，形成一个执行栈。执行栈管理同步任务。</p>
    <h4>异步任务</h4>
    <p>不进入主线程，而是进入任务队列，当主线程中的任务执行完毕，就从任务队列中取出任务放进主线程中来进行执行。由于主线程不断重复的获得任务、执行任务、再获取再执行，所以者种机制被叫做事件循环（Event Loop）。任务队列管理异步任务。</p>

    <h3>异步任务分类：普通任务和微任务</h3>
    <h4>普通任务（之前也俗称宏任务）</h4>
    <p>普通任务-Task（多个独立 task queues，浏览器可实现多队列、不同优先级）。一般由宿主（浏览器、Node）发起。</p>
    <pre>{{ `script(整体代码)
setTimeout
setInterval
IO（（Input / Output，输入输出），主要包含：网络请求、文件读写、数据库操作等）
UI交互事件
postMessage
MessageChannel
setImmediate(Node.js 环境)
` }}</pre>
    <p>PS：script(整体代码) 实际上如果同时存在两个 script 代码块，会首先在执行第一个 script 代码块中的同步代码，如果这个过程中创建了微任务并进入了微任务队列，第一个 script 同步代码执行完之后，会首先去清空微任务队列，再去开启第二个 script 代码块的执行。所以这里应该就可以理解 script（整体代码块）为什么会是普通任务。</p>
    
    <h4>微任务</h4> 
    <p>微任务-microtask（有专门的 microtask queue，规范强制要求执行完一个普通任务-Task之后，必须做微任务检查点，全部清空微任务），一般由 JS 自身发起。</p>
    <pre>{{ `Promise.then/catch/finally
async/await
Object.observe
MutationObserver
process.nextTick(Node.js 环境)
` }}</pre>
    <p> PS：async/await</p>
    <p>ECMAScript2017中添加了async functions和await。 </p>
    <p>async关键字是将一个同步函数变成一个异步函数，并将返回值变为promise。</p>
    <p>而await可以放在任何异步的、基于promise的函数之前。在执行过程中，它会暂停代码在该行上，直到promise完成，然后返回结果值。而在暂停的同时，其他正在等待执行的代码就有机会执行了。</p>
    <p>await后面的函数执行完毕时，await会产生一个微任务(Promise.then是微任务)。但是我们要注意这个微任务产生的时机，它是执行完await之后，直接跳出async函数，执行其他代码(此处就是协程的运作，A暂停执行，控制权交给B)。其他代码执行完毕后，再回到async函数去执行剩下的代码，然后把await后面的代码注册到微任务队列当中。</p>
    <p>await function XXX()，执行顺序如下：先把XXX里的同步执行完，然后会跳出async方法，执行接下来的同步任务，XXX里的异步如promise.then会被添加到微任务队列，执行完这个微任务后会把await方法后面的任务继续添加进微任务队列，并执行这个微任务队列直到清空该队列。</p>
    <p>Promise方法体里的逻辑会当做同步任务立即执行，之后的.then/catch/finally会被添加到微任务队列，then等链式的时候，是一个一个依次添加到微任务队列的，即执行完前面一个待执行下一个的时候才将下一个添加到微任务队列。</p>

    <h3>任务队列</h3>
    <p>任务队列是存放任务的队列，是浏览器用来排队待执行 JS 回调的容器。</p>
    <p>主线程一次只能干一件事。遇到异步，不会立刻执行回调，而是把回调函数包装成一个 task（任务），放到对应的任务队列里。主线程空闲时，事件循环就从任务队列取出任务，放到主线程执行。</p>
    <p>随着浏览器的复杂度急剧提升，W3C<em>不再使用宏队列的说法</em>（拆分成多个更具体的队列）。在目前 chrome的实现中，至少包含了下面的队列:</p>
    <ul class="ul">
      <li><em>微队列</em>：用户存放需要最快执行的任务（微任务），优先级「最高」</li>
      <li><em>交互队列</em>：用于存放用户操作后产生的事件处理任务（UI交互事件），优先级「高」</li>
      <li><em>延时队列</em>：用于存放计时器到达后的回调任务（setTimeout），优先级「普通」</li>
      <li><em>IO队列</em>：用于存放IO操作完成后的回调任务，优先级「普通」</li>
    </ul>
    <h4>IO 队列和延时队列 谁的优先级更高</h4>
    <p>规范没有写死 IO 队列、延时队列 谁的优先级更高，只规定以下硬性规则: </p>
    <ol class="ol">
      <li>同一个任务队列内，必须 FIFO 先进先出；</li> 
      <li>浏览器可以自由选择从哪一个 task 队列取下一个任务（为了用户体验做优化，交互队列（click、键盘）优先级高于它们两个）；</li>
      <li>微任务永远高于所有 task 队列。 </li>
    </ol>
    
    <h3>事件循环</h3>
    <ol class="ol">
      <li>在最开始的时候，渲染主线程会进入一个无限循环</li>
      <li>每一次循环会检查 <em>消息队列-message queue</em> 中是否有任务存在。如果有，就取出第一个任务执行，执行完一个后进入下一次循环；如果没有，则进入休眠状态</li>
      <li>其他所有线程（包括其他进程的线程，如点击动作触发的浏览器进程里的用户交互线程）可以随时向消息队列添加任务。新任务会加到消息队列的末尾。在添加新任务时，如果主线程是休眠状态，则会将其唤醒以继续循环拿取任务</li>
      <li>这样一来，就可以让每个任务有条不紊的、持续的进行下去了。整个过程，被称之为事件循环（消息循环）</li>
    </ol>
