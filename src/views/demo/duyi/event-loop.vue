    <h3>事件循环的执行流程</h3>
    <p>每进行一次循环操作称为 tick，每一次 tick 的任务处理模型是比较复杂的，但关键步骤如下：</p>
    <ol class="ol">
      <li>执行一个普通任务（遇到其他任务，就将其添加到相应的任务队列中）。</li>
      <li>普通任务执行完毕后，立即执行当前微任务队列中的所有微任务（依次执行，如果微任务执行过程中又产生了新的微任务，继续追加执行，直到微任务队列清空）。</li>
      <li>所有微任务执行完毕后，检查是否需要渲染，然后GUI线程接管渲染。</li>  
      <li>渲染完毕后，JS线程继续接管，开始下一个tick。</li> 
    </ol>
    
    <h4>如何理解 JS 的异步?</h4>
    <p>JS是一门单线程的语言，这是因为它运行在浏览器的渲染进程中的渲染主线程中，而渲染主线程只有一个。</p>
    <p>渲染主线程承担着诸多的工作，渲染页面、执行 JS 都在其中运行。如果使用同步的方式，就极有可能导致主线程产生阻塞，从而导致消息队列中的很多其他任务无法得到执行。这样一来，一方面会导致繁忙的主线程白白的消耗时间，另一方面导致页面无法及时更新，给用户造成卡死现象</p>
    <p>所以浏览器采用异步的方式来避免。具体做法是当某些任务发生时，比如计时器（ setTimeout / setInterval ）、网络（ fetch / xhr ）、事件监听（ addEventListener ），主线程将任务交给其他线程去处理，自身立即结束这些任务的执行，转而执行后续代码。当其他线程完成这些任务时，将事先传递的回调函数包装成任务，加入到消息队列的末尾排队，等待主线程调度执行。在这种异步模式下，浏览器永不阻塞，从而最大限度的保证了单线程的流畅运行。</p>

    <h4>任务有优先级吗?</h4>
    <p>任务没有优先级，在消息队列中先进先出，但消息队列是有优先级的</p>
    <p>根据W3C 的最新解释:</p>
    <ul class="ul">
      <li>每个任务都有一个任务类型，同一个类型的任务必须在一个队列，不同类型的任务可以分属于不同的队列。</li>
      <li>在一次事件循环中，浏览器可以根据实际情况从不同的队列中取出任务执行。</li>
      <li>浏览器必须准备好一个微队列，微队列中的任务优先所有其他任务执行。</li>
    </ul>
    
    <h4>阐述一下 JS 的事件循环</h4>
    <p>事件循环又叫做消息循环，是浏览器渲染主线程的工作方式。在Chrome的源码中，它开启一个不会结束的for循环，每次循环从消息队列中取出第一个任务执行，而其他线程只需要在合适的时候将任务加入到队列末尾即可。过去把消息队列简单分为宏队列和微队列，这种说法目前已无法满足复杂的浏览器环境，取而代之的是一种更加灵活多变的处理方式。</p>
    <p>根据 W3C 官方的解释，每个任务有不同的类型，同类型的任务必须在同一个队列，不同的任务可以属于不同的队列。不同任务队列有不同的优先级，在一次事件循环中，由浏览器自行决定取哪一个队列的任务。但浏览器必须有一个微队列，微队列的任务一定具有最高的优先级，必须优先调度执行。</p>

    <h4>JS 中的计时器能做到精确计时吗?为什么?</h4>
    <p>不行，因为:</p>
    <ul class="ol">
      <li>计算机硬件没有原子钟，无法做到精确计时</li> 
      <li>操作系统的计时函数本身就有少量偏差，由于 JS的计时器最终调用的是操作系统的函数，也就携带了这些偏差</li>
      <li>按照 W3C的标准，浏览器实现计时器时，如果嵌套层级超过5层，则会带有4 毫秒的最少时间，这样在计时时间少于4 毫秒时又带来了偏差</li>
      <li>受事件循环的影响，计时器的回调函数只能在主线程空闲时运行，因此又带来了偏差</li>
    </ul>

    <h4>单线程是产生异步的原因，事件循环是解决异步的办法</h4>
